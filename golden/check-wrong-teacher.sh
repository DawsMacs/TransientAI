# The wrong-teacher goldens: what the baby answers on adaptive streams whose teacher is consistently wrong about a share of the facts
# (`baby exam adapt-write --wrong P --repeat F`). Slow (several minutes per stream), so it runs on a schedule and on demand, not on every push
# (`.github/workflows/wrong-teacher.yml`). It exists because a byte comparison on exactly this kind of stream caught a change that the clean
# streams and the whole regression battery missed (see baby/README.md, "Cutting the cost of adapting").
#
#   golden/check-wrong-teacher.sh           generate each stream GOLDEN_RUNS times (default 2), require the runs to agree, then compare with
#                                           golden/wrong-teacher/ and check that the judge found 0 wrong facts about never-wrongly-told facts
#   golden/check-wrong-teacher.sh update    regenerate the goldens from this machine (deliberately, and say why in the commit)
#
# Exit status: 0 all match; 1 a difference (or damage elsewhere); 2 an output could not be generated; 3 the runs on this machine disagree.
# Reference platform: Linux x86_64 glibc, like golden/check.sh. The streams, as `name:seed:wrong-rate` (WT_CASES overrides; CI runs one per job):

set -u
cd "$(dirname "$0")/.." || exit 2

CASES=${WT_CASES:-"w0.2-seed3:3:0.2 w0.1-seed2:2:0.1"}
REPEAT=0.3
RUNS=${GOLDEN_RUNS:-2}
WORK=target/golden-work-wrong-teacher

baby() { cargo run --quiet --release --offline --bin baby -- "$@"; }

mkdir -p "$WORK"
status=0
for c in $CASES; do
    name=${c%%:*}; rest=${c#*:}; seed=${rest%%:*}; wrong=${rest#*:}
    dir="$WORK/$name"
    baby exam adapt-write "$dir" --seed "$seed" --wrong "$wrong" --repeat "$REPEAT" >/dev/null || { echo "could not write the stream $name"; exit 2; }
    i=1
    while [ "$i" -le "$RUNS" ]; do
        echo "$name: run $i of $RUNS ..."
        EXAM_NO_JOULES=1 baby exam adapt-run "$dir" --seed "$seed" --out "$WORK/$name.run$i.tsv" >"$WORK/$name.run$i.log" 2>&1 || { echo "could not run $name (run $i)"; exit 2; }
        tr -d '\r' <"$WORK/$name.run$i.tsv" >"$WORK/$name.run$i.lf" && mv "$WORK/$name.run$i.lf" "$WORK/$name.run$i.tsv"
        i=$((i + 1))
    done
    i=2
    while [ "$i" -le "$RUNS" ]; do
        if ! cmp -s "$WORK/$name.run1.tsv" "$WORK/$name.run$i.tsv"; then
            echo "NOT REPRODUCIBLE on this machine: $name differs between run 1 and run $i (look for hash-map ordering first)."
            exit 3
        fi
        i=$((i + 1))
    done
    echo "$name: the $RUNS runs agree"
    # the judge's own verdict: the teacher's mistakes must not have damaged anything it was not wrong about
    if ! grep -q "never wrongly told (must be 0): 0" "$WORK/$name.run1.log"; then
        echo "DAMAGE ELSEWHERE in $name:"; grep -E "never wrongly told|offender" "$WORK/$name.run1.log" | head -5
        status=1
    fi
    if [ "${1:-}" = "update" ]; then
        cp "$WORK/$name.run1.tsv" "golden/wrong-teacher/replies-$name.tsv"
        echo "updated golden/wrong-teacher/replies-$name.tsv"
    elif cmp -s <(tr -d '\r' <"golden/wrong-teacher/replies-$name.tsv") "$WORK/$name.run1.tsv"; then
        echo "golden OK:      replies-$name.tsv"
    else
        n=$(diff <(tr -d '\r' <"golden/wrong-teacher/replies-$name.tsv") "$WORK/$name.run1.tsv" | grep -c '^>')
        echo "golden DIFFERS: replies-$name.tsv ($n lines differ)"
        diff <(tr -d '\r' <"golden/wrong-teacher/replies-$name.tsv") "$WORK/$name.run1.tsv" | head -10
        status=1
    fi
done
[ "${1:-}" = "update" ] && { { echo "Regenerated by golden/check-wrong-teacher.sh update on $(date -u +%Y-%m-%d)."; echo "rustc: $(rustc --version)"; echo "host:  $(uname -srm 2>/dev/null || echo unknown)"; echo "streams: $CASES (repeat $REPEAT), runs that agreed: $RUNS"; } >golden/wrong-teacher/PROVENANCE.txt; cat golden/wrong-teacher/PROVENANCE.txt; exit 0; }
exit $status
